//! Fuzz target logic for the `flatbuffers` Rust verifier and reader.
//!
//! The interesting property of the Rust runtime is that a buffer which passes
//! `flatbuffers::root::<T>()` is supposed to be safe to read through the
//! generated **safe** accessors: the accessors themselves contain no `unsafe`
//! for the user, they only rely on the verifier having proven that every offset,
//! vtable and vector the reader follows is inside the buffer.
//!
//! This target therefore does exactly that: verify arbitrary bytes and then walk
//! the whole object graph with safe accessors only, including the table ->
//! vtable -> size path, which is where a verifier/reader disagreement shows up
//! first as an out-of-bounds read.
//!
//! The logic lives in a library target (`fuzz_one_input`) so the same code can be
//! driven by runners other than libFuzzer -- `cargo miri run`, for instance,
//! detects the out-of-bounds access even when a release build (where the
//! `debug_assert!`s in `endian_scalar.rs` are compiled out) only reads garbage.

#![deny(unsafe_code)]

use flatbuffers::Table;

// Bindings for flatbuffers_rust_verifier.fbs, regenerated by build.sh with the
// flatc built from the same checkout, so this target always exercises the
// current code generator.
//
// `unsafe_code` is allowed here because flatc emits the usual `unsafe { .. }`
// blocks around the `Table` reads it knows the verifier has checked; everything
// written by hand in this file stays free of `unsafe`.
#[allow(clippy::all, unused_imports, dead_code, unsafe_code)]
#[path = "flatbuffers_rust_verifier_generated.rs"]
mod generated;

use generated::flatbuffers_rust_verifier::{Any, Inner, Leaf, Root};

/// Verifies `data` and walks the resulting object graph.
///
/// Verification failures are the expected outcome for most inputs and are not
/// interesting; only a crash while reading a buffer that verified is.
pub fn fuzz_one_input(data: &[u8]) {
    // Copy into an exactly sized allocation first: libFuzzer is free to hand out
    // a buffer with spare capacity, and an overread that lands in that spare
    // capacity would go unnoticed.  With a `Vec` of exactly `data.len()` bytes
    // every read past the end of the input lands in an ASan redzone.
    let buf = data.to_vec();

    // Both public entry points: a plain root and a size prefixed one.
    if let Ok(root) = flatbuffers::root::<Root>(&buf) {
        walk_root(&root);
    }

    if let Ok(root) = flatbuffers::size_prefixed_root::<Root>(&buf) {
        walk_root(&root);
    }
}

/// Reads the vtable of `table` and both of its mandatory header fields.
///
/// `Table::vtable` is a safe function and so are the `VTable` methods called on
/// its result; their safety rests entirely on the verifier having accepted the
/// `soffset` at `table.loc()` and the vtable it points to.  The two header
/// fields sit at `loc()` and `loc() + 2`, so a vtable that the verifier let
/// through while being shorter than that makes these reads escape the buffer.
fn touch_vtable(table: &Table<'_>) {
    let vtable = table.vtable();
    let _ = vtable.num_bytes();
    let _ = vtable.object_inline_num_bytes();
}

fn walk_leaf(leaf: &Leaf<'_>) {
    touch_vtable(&leaf._tab);

    let _ = leaf.id();
    let _ = leaf.name().map(str::len);
    let _ = leaf.flags().map(|v| v.len());
    let _ = leaf.color();
    let _ = leaf.pos();
    if let Some(weights) = leaf.weights() {
        if !weights.is_empty() {
            let _ = weights.get(0);
            let _ = weights.get(weights.len() - 1);
        }
    }
}

fn walk_inner(inner: &Inner<'_>) {
    touch_vtable(&inner._tab);

    let _ = inner.label().map(str::len);
    let _ = inner.opt();
    if let Some(values) = inner.values() {
        if !values.is_empty() {
            let _ = values.get(0);
            let _ = values.get(values.len() - 1);
        }
    }
    if let Some(doubles) = inner.doubles() {
        if !doubles.is_empty() {
            let _ = doubles.get(0);
        }
    }
    if let Some(blobs) = inner.blobs() {
        if !blobs.is_empty() {
            let _ = blobs.get(0);
        }
    }
    if let Some(small) = inner.small() {
        if !small.is_empty() {
            let _ = small.get(0);
        }
    }
    if let Some(tags) = inner.tags() {
        for tag in tags.iter() {
            let _ = tag.len();
        }
    }
    if let Some(leaves) = inner.leaves() {
        for leaf in leaves.iter() {
            walk_leaf(&leaf);
        }
    }
}

fn walk_root(root: &Root<'_>) {
    touch_vtable(&root._tab);

    let _ = root.name().map(str::len);
    let _ = root.req_str().len();
    let _ = root.abc();
    let _ = root.ulongv().map(|v| v.len());
    let _ = root.ushortv().map(|v| v.len());
    let _ = root.boolv().map(|v| v.len());
    let _ = root.bytes8().map(|v| v.len());
    if let Some(ids) = root.ids() {
        if !ids.is_empty() {
            let _ = ids.get(0);
            let _ = ids.get(ids.len() - 1);
        }
    }
    if let Some(raw) = root.raw() {
        if !raw.is_empty() {
            let _ = raw.get(0);
        }
    }
    if let Some(vecs) = root.vecs() {
        for vec in vecs.iter() {
            let _ = vec.x();
        }
    }
    if let Some(child) = root.child() {
        walk_inner(&child);
    }
    if let Some(nest) = root.nest() {
        walk_inner(&nest);
    }
    if let Some(kids) = root.kids() {
        for kid in kids.iter() {
            walk_inner(&kid);
        }
    }

    // The union: the typed accessors only build a table when the discriminant
    // matches, but the untyped `choice()` accessor hands out a bare `Table` for
    // whatever the discriminant is, including one this reader does not know, so
    // that table has to be traversable too.
    match root.choice_type() {
        Any::Leaf => {
            if let Some(leaf) = root.choice_as_leaf() {
                walk_leaf(&leaf);
            }
        }
        Any::Inner => {
            if let Some(inner) = root.choice_as_inner() {
                walk_inner(&inner);
            }
        }
        _ => {}
    }
    if let Some(choice) = root.choice() {
        touch_vtable(&choice);
    }
}
